/**
 * Core types for the two-player, two-action effort game.
 *
 * Outcome keys always list Student A's action first, then Student B's:
 * `HL` means A chose High effort and B chose Low effort.
 */

export type Action = 'H' | 'L';
export type Player = 'A' | 'B';
export type OutcomeKey = 'HH' | 'HL' | 'LH' | 'LL';

export const ACTIONS: readonly Action[] = ['H', 'L'];
export const OUTCOMES: readonly OutcomeKey[] = ['HH', 'HL', 'LH', 'LL'];

/** Payoffs for one outcome: `a` goes to Student A, `b` to Student B. */
export interface Cell {
  a: number;
  b: number;
}

export type PayoffMatrix = Record<OutcomeKey, Cell>;

/** Hard limits for any payoff, whether typed by the user or generated by the formula. */
export const PAYOFF_MIN = -100;
export const PAYOFF_MAX = 100;

export function outcomeKey(a: Action, b: Action): OutcomeKey {
  return `${a}${b}` as OutcomeKey;
}

export function splitOutcome(key: OutcomeKey): [Action, Action] {
  return [key[0] as Action, key[1] as Action];
}

export function otherAction(action: Action): Action {
  return action === 'H' ? 'L' : 'H';
}

/** The illustrative matrix from the project brief. */
export const DEFAULT_MATRIX: PayoffMatrix = {
  HH: { a: 6, b: 6 },
  HL: { a: 2, b: 8 },
  LH: { a: 8, b: 2 },
  LL: { a: 3, b: 3 },
};

export function cloneMatrix(m: PayoffMatrix): PayoffMatrix {
  return {
    HH: { ...m.HH },
    HL: { ...m.HL },
    LH: { ...m.LH },
    LL: { ...m.LL },
  };
}

export function matricesEqual(x: PayoffMatrix, y: PayoffMatrix): boolean {
  return OUTCOMES.every((k) => x[k].a === y[k].a && x[k].b === y[k].b);
}

